import "dotenv/config";
import fs from "fs";
import path from "path";
import { createPublicClient, http, keccak256 } from "viem";
import { polygonAmoy } from "viem/chains";

function requireEnv(name) {
  const value = process.env[name];

  if (!value || value.trim() === "") {
    throw new Error(`Missing environment variable: ${name}`);
  }

  return value.trim();
}

function hexToBytesLength(hex) {
  if (!hex || hex === "0x") return 0;
  const cleanHex = hex.startsWith("0x") ? hex.slice(2) : hex;
  return cleanHex.length / 2;
}

function bytesToKb(bytes) {
  return Number((bytes / 1024).toFixed(3));
}

function percentOfLimit(bytes, limit) {
  return Number(((bytes / limit) * 100).toFixed(2));
}

function ensureDir(dirPath) {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

async function main() {
  console.log("==================================================");
  console.log("SMART CONTRACT PROGRAM MEMORY SIZE - POLYGON AMOY");
  console.log("==================================================");

  const rpcUrl = requireEnv("AMOY_RPC_URL");
  const contractAddress = requireEnv("CONTRACT_ADDRESS");

  const artifactPath = path.join(
    process.cwd(),
    "artifacts",
    "contracts",
    "GydPlatform.sol",
    "GydPlatform.json"
  );

  const sourcePath = path.join(
    process.cwd(),
    "contracts",
    "GydPlatform.sol"
  );

  if (!fs.existsSync(artifactPath)) {
    throw new Error(
      `Artifact not found at ${artifactPath}. Please run: npx hardhat compile`
    );
  }

  const artifactRaw = fs.readFileSync(artifactPath, "utf8");
  const artifact = JSON.parse(artifactRaw);

  const deployBytecode = artifact.bytecode || "0x";
  const compiledRuntimeBytecode = artifact.deployedBytecode || "0x";
  const abi = artifact.abi || [];

  const publicClient = createPublicClient({
    chain: polygonAmoy,
    transport: http(rpcUrl),
  });

  const chainId = await publicClient.getChainId();

  if (chainId !== 80002) {
    throw new Error(`Wrong chain ID. Expected 80002, got ${chainId}`);
  }

  const onChainBytecode = await publicClient.getBytecode({
    address: contractAddress,
  });

  const deployBytecodeBytes = hexToBytesLength(deployBytecode);
  const compiledRuntimeBytes = hexToBytesLength(compiledRuntimeBytecode);
  const onChainRuntimeBytes = hexToBytesLength(onChainBytecode || "0x");

  const abiSizeBytes = Buffer.byteLength(JSON.stringify(abi), "utf8");
  const artifactSizeBytes = Buffer.byteLength(artifactRaw, "utf8");

  const sourceSizeBytes = fs.existsSync(sourcePath)
    ? fs.statSync(sourcePath).size
    : 0;

  const evmContractSizeLimitBytes = 24576;

  const summary = {
    network: "Polygon Amoy",
    chainId,
    contractAddress,
    contractName: "GydPlatform",
    measuredAt: new Date().toISOString(),
    sourceFile: fs.existsSync(sourcePath) ? sourcePath : "not found",
    artifactFile: artifactPath,
    sourceCodeSize: {
      bytes: sourceSizeBytes,
      kilobytes: bytesToKb(sourceSizeBytes),
    },
    abiSize: {
      bytes: abiSizeBytes,
      kilobytes: bytesToKb(abiSizeBytes),
    },
    artifactJsonSize: {
      bytes: artifactSizeBytes,
      kilobytes: bytesToKb(artifactSizeBytes),
    },
    deployBytecodeSize: {
      bytes: deployBytecodeBytes,
      kilobytes: bytesToKb(deployBytecodeBytes),
      description:
        "Creation bytecode used during deployment. This includes constructor/deployment code.",
    },
    compiledRuntimeBytecodeSize: {
      bytes: compiledRuntimeBytes,
      kilobytes: bytesToKb(compiledRuntimeBytes),
      percentageOfEvmContractSizeLimit: percentOfLimit(
        compiledRuntimeBytes,
        evmContractSizeLimitBytes
      ),
      description:
        "Runtime bytecode generated by the compiler and stored as deployedBytecode in the artifact.",
    },
    onChainRuntimeBytecodeSize: {
      bytes: onChainRuntimeBytes,
      kilobytes: bytesToKb(onChainRuntimeBytes),
      percentageOfEvmContractSizeLimit: percentOfLimit(
        onChainRuntimeBytes,
        evmContractSizeLimitBytes
      ),
      bytecodeHash: onChainBytecode ? keccak256(onChainBytecode) : "",
      description:
        "Actual runtime bytecode retrieved from the deployed contract on Polygon Amoy.",
    },
    evmContractSizeLimit: {
      bytes: evmContractSizeLimitBytes,
      kilobytes: bytesToKb(evmContractSizeLimitBytes),
      description:
        "Maximum runtime contract bytecode size limit used as reference for EVM contracts.",
    },
  };

  console.log("");
  console.log("Network                    :", summary.network);
  console.log("Chain ID                   :", summary.chainId);
  console.log("Contract Address           :", summary.contractAddress);
  console.log("Contract Name              :", summary.contractName);

  console.log("");
  console.log("Source Code Size           :", `${summary.sourceCodeSize.bytes} bytes`, `(${summary.sourceCodeSize.kilobytes} KB)`);
  console.log("ABI Size                   :", `${summary.abiSize.bytes} bytes`, `(${summary.abiSize.kilobytes} KB)`);
  console.log("Artifact JSON Size         :", `${summary.artifactJsonSize.bytes} bytes`, `(${summary.artifactJsonSize.kilobytes} KB)`);

  console.log("");
  console.log("Deploy Bytecode Size       :", `${summary.deployBytecodeSize.bytes} bytes`, `(${summary.deployBytecodeSize.kilobytes} KB)`);
  console.log("Compiled Runtime Bytecode  :", `${summary.compiledRuntimeBytecodeSize.bytes} bytes`, `(${summary.compiledRuntimeBytecodeSize.kilobytes} KB)`);
  console.log("On-chain Runtime Bytecode  :", `${summary.onChainRuntimeBytecodeSize.bytes} bytes`, `(${summary.onChainRuntimeBytecodeSize.kilobytes} KB)`);
  console.log("EVM Runtime Size Limit     :", `${summary.evmContractSizeLimit.bytes} bytes`, `(${summary.evmContractSizeLimit.kilobytes} KB)`);

  console.log("");
  console.log("Runtime Bytecode Usage     :", `${summary.onChainRuntimeBytecodeSize.percentageOfEvmContractSizeLimit}% of EVM limit`);
  console.log("On-chain Bytecode Hash     :", summary.onChainRuntimeBytecodeSize.bytecodeHash || "-");

  const outputDir = path.join(process.cwd(), "measurements");
  ensureDir(outputDir);

  const timestamp = new Date().toISOString().replace(/[:.]/g, "-");

  const jsonPath = path.join(
    outputDir,
    `blockchain-program-memory-amoy-${timestamp}.json`
  );

  const csvPath = path.join(
    outputDir,
    `blockchain-program-memory-amoy-${timestamp}.csv`
  );

  fs.writeFileSync(jsonPath, JSON.stringify(summary, null, 2));

  const csvRows = [
    ["Metric", "Bytes", "Kilobytes", "Notes"],
    [
      "Source Code Size",
      summary.sourceCodeSize.bytes,
      summary.sourceCodeSize.kilobytes,
      "Solidity source file size",
    ],
    [
      "ABI Size",
      summary.abiSize.bytes,
      summary.abiSize.kilobytes,
      "Application Binary Interface size",
    ],
    [
      "Artifact JSON Size",
      summary.artifactJsonSize.bytes,
      summary.artifactJsonSize.kilobytes,
      "Compiled artifact file size",
    ],
    [
      "Deploy Bytecode Size",
      summary.deployBytecodeSize.bytes,
      summary.deployBytecodeSize.kilobytes,
      "Creation bytecode used during deployment",
    ],
    [
      "Compiled Runtime Bytecode Size",
      summary.compiledRuntimeBytecodeSize.bytes,
      summary.compiledRuntimeBytecodeSize.kilobytes,
      "Runtime bytecode from compiled artifact",
    ],
    [
      "On-chain Runtime Bytecode Size",
      summary.onChainRuntimeBytecodeSize.bytes,
      summary.onChainRuntimeBytecodeSize.kilobytes,
      "Actual runtime bytecode retrieved from Polygon Amoy",
    ],
    [
      "EVM Runtime Contract Size Limit",
      summary.evmContractSizeLimit.bytes,
      summary.evmContractSizeLimit.kilobytes,
      "Reference maximum runtime bytecode size",
    ],
  ];

  fs.writeFileSync(csvPath, csvRows.map((row) => row.join(",")).join("\n"));

  console.log("");
  console.log("Measurement JSON saved to :", jsonPath);
  console.log("Measurement CSV saved to  :", csvPath);

  console.log("");
  console.log("Done.");
}

main().catch((error) => {
  console.error("");
  console.error("Measurement failed.");
  console.error(error);
  process.exitCode = 1;
});